"""VLM-as-Judge evaluator — scores final ad image using gpt-5.4 vision.

Reads two image paths from ops DB result node:
  - background_image_path: T2I background only (for hallucination + composition checks)
  - output_path: final ad with PIL text overlay (for readability + commercial viability)

Writes score_items (evaluator_type="vlm") to eval DB.
Requires: LLM_ENABLE_API_CALL=true + OPENAI_API_KEY set.
Model: LLM_OPENAI_VISION_MODEL (falls back to LLM_OPENAI_TEXT_MODEL_FULL → gpt-5.4).
"""

from __future__ import annotations

import base64
import json
import os
import sqlite3
from contextlib import contextmanager
from typing import Any, Generator

from orchestrator.app.core.config import _get_bool, _get_env
from orchestrator.eval.config import EVAL_DB_PATH, OPS_DB_PATH
from orchestrator.eval.eval_db import EvalDBWriter

# (item_id, description, use_background_image)
# use_background_image=True  → T2I background (no text overlay)
# use_background_image=False → final ad output (with PIL text composited)
_VLM_ITEMS: list[tuple[str, str, bool]] = [
    (
        "III-6",
        "Visual brand tone match: Does the overall visual style (color palette, mood, lighting) "
        "match the brand type and target audience described in the marketing context?",
        False,   # final ad — full context visible
    ),
    (
        "IV-6",
        "Text hallucination check (OCR Verification): Does the T2I background image contain "
        "ANY visible text, characters, letters, numbers, or text-like artifacts generated by "
        "the diffusion model? Score 5 if completely text-free, 1 if heavy text artifacts.",
        True,    # background only — detect diffusion hallucinated text
    ),
    (
        "IV-7",
        "Visual composition quality (Visual Quality): Is the background image free of bizarre "
        "distortions (finger errors, uncanny valley artifacts), and does it have a stable, "
        "balanced composition with clear focal point?",
        True,    # background only — assess T2I generation quality
    ),
    (
        "IV-8",
        "Readability and non-obstruction (Readability): In the final composited ad, does the "
        "overlaid copy text avoid covering the key product or subject, and does it remain "
        "legible against the background (not buried in busy areas)?",
        False,   # final ad — PIL text composited on background
    ),
    (
        "IV-9",
        "Commercial viability (Commercial Viability): Is the final combined result (image + copy) "
        "at a quality level ready for immediate use in Instagram feeds, banners, or other real "
        "marketing channels without further editing?",
        False,   # final ad — holistic commercial judgment
    ),
]

_VLM_SYSTEM_PROMPT = (
    "You are a visual quality evaluator for AI-generated advertising images. "
    "Score the given visual criterion on a 1-5 scale based solely on what you observe in the image.\n"
    "Rubric: 5=Excellent, 4=Good minor gap, 3=Acceptable notable issue, 2=Poor significant failure, 1=Very poor/unusable.\n"
    'Return JSON only: {"score": <int 1-5>, "reason": "<one sentence describing what you observe>"}'
)


@contextmanager
def _ops_conn(db_path: str) -> Generator[sqlite3.Connection, None, None]:
    conn = sqlite3.connect(db_path)
    conn.row_factory = sqlite3.Row
    try:
        yield conn
    finally:
        conn.close()


def _fetch_result_images(conn: sqlite3.Connection, job_id: str) -> tuple[str | None, str | None]:
    """Return (final_output_path, background_image_path) from result node output_snapshot."""
    row = conn.execute(
        """SELECT nso.output_snapshot
           FROM node_state_outputs nso
           JOIN node_executions ne ON ne.id = nso.node_exec_id
           WHERE ne.job_id=? AND ne.node_name='result' AND ne.status='completed'
           ORDER BY ne.id DESC LIMIT 1""",
        (job_id,),
    ).fetchone()
    if not row or not row["output_snapshot"]:
        return None, None
    try:
        payload = json.loads(row["output_snapshot"])
        rp = payload.get("result_payload") or payload
        final_path = rp.get("output_path") or rp.get("final_image_path")
        bg_path = rp.get("background_image_path")
        return final_path, bg_path
    except Exception:
        return None, None


def _fetch_context_summary(conn: sqlite3.Connection, job_id: str) -> str:
    """Get brief marketing context string for III-6 brand tone criterion."""
    row = conn.execute(
        """SELECT nso.output_snapshot
           FROM node_state_outputs nso
           JOIN node_executions ne ON ne.id = nso.node_exec_id
           WHERE ne.job_id=? AND ne.node_name='validator' AND ne.status='completed'
           ORDER BY ne.id DESC LIMIT 1""",
        (job_id,),
    ).fetchone()
    if not row or not row["output_snapshot"]:
        return "(no context available)"
    try:
        data = json.loads(row["output_snapshot"])
        ctx = data.get("context") or {}
        parts = [f"{k}: {ctx[k]}" for k in ("business_type", "product", "target_audience", "promotion_goal", "tone") if ctx.get(k)]
        return ", ".join(parts) if parts else "(context fields missing)"
    except Exception:
        return "(context parse error)"


def _encode_image(image_path: str) -> tuple[str, str] | None:
    """Return (mime_type, base64_str) or None if file unreadable."""
    if not image_path or not os.path.isfile(image_path):
        return None
    ext = os.path.splitext(image_path)[1].lower()
    mime = {".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".png": "image/png", ".webp": "image/webp"}.get(ext, "image/png")
    try:
        with open(image_path, "rb") as f:
            return mime, base64.b64encode(f.read()).decode("utf-8")
    except Exception:
        return None


def _call_vlm(
    item_id: str,
    description: str,
    context_summary: str,
    mime: str,
    b64: str,
    api_key: str,
    model: str,
    timeout: int = 60,
) -> dict[str, Any] | None:
    """Call OpenAI Responses API with image input. Returns {"score": int, "reason": str} or None."""
    try:
        from openai import OpenAI
    except ImportError:
        return None

    user_text = f"{_VLM_SYSTEM_PROMPT}\n\nCriterion [{item_id}]: {description}"
    if item_id == "III-6":
        user_text += f"\n\nMarketing context: {context_summary}"

    try:
        client = OpenAI(api_key=api_key, timeout=timeout)
        response = client.responses.create(
            model=model,
            input=[
                {
                    "role": "user",
                    "content": [
                        {"type": "input_text", "text": user_text},
                        {"type": "input_image", "image_url": f"data:{mime};base64,{b64}"},
                    ],
                }
            ],
            text={"format": {"type": "json_object"}},
        )
        raw = getattr(response, "output_text", None) or ""
        return json.loads(raw) if raw else None
    except Exception:
        return None


def run_vlm_eval(
    eval_id: str,
    job_id: str,
    ops_db_path: str = OPS_DB_PATH,
    eval_db_path: str = EVAL_DB_PATH,
    api_key: str | None = None,
    model: str | None = None,
) -> list[str]:
    """Score 5 visual items on the generated ad using GPT-5.4 vision.

    Items:
        III-6 (brand tone)        — final ad image
        IV-6  (text hallucination) — background image (T2I only)
        IV-7  (composition)        — background image (T2I only)
        IV-8  (readability)        — final ad image (with PIL text overlay)
        IV-9  (commercial viability) — final ad image

    Returns list of scored item_ids.
    Raises RuntimeError if API disabled, key missing, or no images found.
    """
    if not _get_bool("LLM_ENABLE_API_CALL", False):
        raise RuntimeError("LLM_ENABLE_API_CALL is false — set to true to run vlm eval")

    resolved_key = api_key or _get_env("OPENAI_API_KEY", "")
    if not resolved_key:
        raise RuntimeError("OPENAI_API_KEY not set")

    resolved_model = (
        model
        or _get_env("LLM_OPENAI_VISION_MODEL", "")
        or _get_env("LLM_OPENAI_TEXT_MODEL_FULL", "")
        or "gpt-5.4"
    )
    # gpt-5.4-nano supports image input but is not designed for nuanced visual quality
    # evaluation — it's optimized for simple classification/extraction. Warn and fall back.
    if "nano" in resolved_model:
        import warnings
        warnings.warn(
            f"VLM eval model '{resolved_model}' is gpt-5.4-nano which is not suitable for "
            "sophisticated visual quality evaluation. Set LLM_OPENAI_VISION_MODEL=gpt-5.4 "
            "or LLM_OPENAI_TEXT_MODEL_FULL=gpt-5.4 for accurate results.",
            UserWarning,
            stacklevel=2,
        )
    timeout = int(_get_env("LLM_REQUEST_TIMEOUT_SECONDS", "60") or "60")

    writer = EvalDBWriter(eval_db_path)
    scored: list[str] = []

    with _ops_conn(ops_db_path) as conn:
        final_path, bg_path = _fetch_result_images(conn, job_id)
        if not final_path and not bg_path:
            raise RuntimeError(f"No output images found for job_id={job_id} — pipeline must complete first")

        final_encoded = _encode_image(final_path) if final_path else None
        bg_encoded = _encode_image(bg_path) if bg_path else None
        context_summary = _fetch_context_summary(conn, job_id)

        for item_id, description, use_bg in _VLM_ITEMS:
            encoded = bg_encoded if use_bg else final_encoded
            if encoded is None:
                # Fallback: try the other image if primary unavailable
                encoded = final_encoded if use_bg else bg_encoded
            if encoded is None:
                continue

            mime, b64 = encoded
            result = _call_vlm(item_id, description, context_summary, mime, b64, resolved_key, resolved_model, timeout)
            if result is None:
                continue

            score = result.get("score")
            reason = result.get("reason", "")
            if not isinstance(score, int) or not (1 <= score <= 5):
                continue

            writer.write_score_item(eval_id, item_id, score, notes=reason, evaluator_type="vlm")
            scored.append(item_id)

    return scored
